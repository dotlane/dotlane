#!/usr/bin/env bash
# Writes NOTICE: Dotlane's own notice, every module the released binary embeds with its licence
# (from go-licenses, for the macOS build), and the NOTICE files those modules ship, verbatim, as
# the Apache License 2.0 (section 4d) asks.
#
#   scripts/notice.sh           rewrite NOTICE
#   scripts/notice.sh --check   fail if NOTICE is out of date (scripts/check.sh runs this)
#
# Module versions are left out, so only a new or removed module, or a changed licence or NOTICE
# file, changes the output.
set -euo pipefail
export LC_ALL=C # the same sort order on macOS and Linux
cd "$(dirname "$0")/.."

GO_LICENSES_VERSION=v1.6.0
# Built for this machine, into a cache folder like scripts/check.sh's tools; only the analysis
# below targets macOS.
go_licenses=${XDG_CACHE_HOME:-$HOME/.cache}/dotlane-check/go-licenses-$GO_LICENSES_VERSION/go-licenses
if [[ ! -x $go_licenses ]]; then
  env -u GOOS -u GOARCH GOBIN="$(dirname "$go_licenses")" go install "github.com/google/go-licenses@$GO_LICENSES_VERSION"
fi
target=(env GOOS=darwin GOARCH=arm64) # the Intel build embeds the same modules

render() {
  cat <<'EOF'
Dotlane
Copyright 2026 Pedro Silva

Licensed under the Apache License, Version 2.0 (see LICENSE).

The dotlane binary embeds Caddy (https://caddyserver.com), Copyright 2015 Matthew Holt and The
Caddy Authors, also under the Apache License, Version 2.0, and the other modules listed below,
each under its own licence. Their source is at each module's path (for example
https://pkg.go.dev/github.com/caddyserver/caddy/v2); this includes the one module under the
Mozilla Public License 2.0, github.com/go-sql-driver/mysql, whose source is unmodified.

Generated by scripts/notice.sh; do not edit by hand.

EOF
  echo "Modules embedded in the dotlane binary"
  echo "======================================"
  echo
  local report log
  log=$(mktemp)
  report=$("${target[@]}" "$go_licenses" report ./cmd/dotlane 2>"$log") || true
  # It warns about every non-Go file it skips, so its log is shown only when it fails.
  [[ -n $report ]] || { echo "go-licenses printed nothing:" >&2; grep -v '^W' "$log" >&2; rm -f "$log"; return 1; }
  rm -f "$log"
  grep -v '^github.com/dotlane/dotlane,' <<<"$report" | awk -F, '{ printf "%-60s %s\n", $1, $3 }' | sort
  echo
  echo "Notices of embedded modules"
  echo "==========================="
  local mod dir f
  while read -r mod dir; do
    [[ -n $dir && $mod != github.com/dotlane/dotlane ]] || continue
    while IFS= read -r f; do
      printf '\n--- %s (%s)\n\n' "$mod" "$(basename "$f")"
      cat "$f"
    done < <(find "$dir" -maxdepth 1 -type f -iname 'notice*' | sort)
  done < <("${target[@]}" go list -deps -f '{{with .Module}}{{.Path}} {{.Dir}}{{end}}' ./cmd/dotlane | sort -u)
}

out=$(render)
if [[ ${1:-} == --check ]]; then
  if ! diff -u NOTICE - <<<"$out"; then
    echo "NOTICE is out of date: run scripts/notice.sh" >&2
    exit 1
  fi
  exit 0
fi
printf '%s\n' "$out" > NOTICE
